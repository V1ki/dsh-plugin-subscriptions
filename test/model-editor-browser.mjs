// PLAYWRIGHT_PATH=/path/to/playwright node test/model-editor-browser.mjs
import assert from 'node:assert/strict'
import { readdir, readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
const dependencies = await readdir('node_modules/.pnpm')
const packagePath = name => resolve('node_modules/.pnpm', dependencies.find(entry => entry.startsWith(`${name}@`)), 'node_modules', name)
const { build } = await import(pathToFileURL(`${packagePath('rolldown')}/dist/index.mjs`))
const { chromium } = await import(pathToFileURL(`${process.env.PLAYWRIGHT_PATH}/index.mjs`))
const bundle = await build({ input: 'test/model-editor-browser.fixture.tsx', plugins: [{ name: 'test-css', load(id) { return id.endsWith('Tooltip.module.css') ? 'export default { bubble: "bubble", label: "label" }' : id.endsWith('.css') ? 'export default {}' : null } }], resolve: { alias: { 'react-dom/client': `${packagePath('react-dom')}/client.js` } }, transform: { define: { 'process.env.NODE_ENV': '"production"' } }, output: { format: 'iife' }, write: false })
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) })
try {
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setContent('<div id="root"></div>')
  await page.addStyleTag({ content: await readFile('node_modules/@deepseek-ai/dsh-client-ui-primitives/lib/Tooltip.module.css', 'utf8') })
  await page.addScriptTag({ content: bundle.output.find(file => file.type === 'chunk').code })
  const heading = page.getByRole('heading', { name: 'Edit model list' })
  const refresh = page.getByRole('button', { name: 'Refresh', exact: true })
  assert.equal(await refresh.locator('svg[aria-hidden="true"]').count(), 1)
  assert.equal(await heading.evaluate(el => el.parentElement === document.querySelector('button.dsh-subscription-quiet')?.parentElement), true, 'refresh shares the heading row')
  const buttons = page.locator('button[aria-expanded]')
  await buttons.first().waitFor()
  assert.deepEqual(await buttons.locator('.dsh-subscription-model-name').allTextContents(), ['gone (Currently unavailable)', 'Alpha', 'Aardvark'])
  assert.deepEqual(await buttons.locator('.dsh-subscription-model-id').allTextContents(), ['ID: gone', 'ID: alpha', 'ID: beta'])
  assert.deepEqual(await buttons.locator('.dsh-subscription-model-action').allTextContents(), ['Expand', 'Expand', 'Expand'])
  const rows = await buttons.evaluateAll(els => els.map(el => el.parentElement.getBoundingClientRect().top))
  assert.ok(rows[1] - rows[0] <= 40, 'collapsed rows remain compact')
  assert.deepEqual(await buttons.evaluateAll(els => els.map(el => getComputedStyle(el.parentElement.parentElement).borderBottomStyle)), ['none', 'none', 'none'])
  const visual = await buttons.first().evaluate(el => { const css = getComputedStyle(el); return { justify: css.justifyContent, border: css.borderTopWidth, align: css.textAlign } })
  assert.deepEqual(visual, { justify: 'flex-start', border: '0px', align: 'left' })
  const modelHelp = page.getByRole('button', { name: 'About Edit model list' })
  await modelHelp.click()
  const modelTip = page.getByRole('tooltip')
  await modelTip.waitFor({ state: 'visible' })
  assert.match(await modelTip.textContent(), /Configure model visibility, default reasoning effort/)
  assert.equal(await modelTip.evaluate(el => !!el.closest('dialog:modal')), true)
  assert.equal(await modelTip.evaluate(el => { const r = el.getBoundingClientRect(); const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return hit === el || el.contains(hit) }), true)
  await page.keyboard.press('Escape')
  await modelTip.waitFor({ state: 'hidden' })
  const help = page.getByRole('button', { name: 'About Provider tools' })
  await help.click()
  const tooltip = page.getByRole('tooltip')
  await tooltip.waitFor({ state: 'visible' })
  assert.match(await tooltip.textContent(), /Changes apply only to sessions created after saving/)
  assert.equal(await tooltip.evaluate(el => !!el.closest('dialog:modal')), true)
  assert.equal(await tooltip.evaluate(el => { const r = el.getBoundingClientRect(); const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return hit === el || el.contains(hit) }), true, 'tooltip is visible and hit-testable above the modal')
  await page.keyboard.press('Escape')
  const tools = page.locator('.dsh-subscription-tools')
  assert.equal(await tools.locator('label svg[aria-hidden="true"]').count(), 4)
  const toolLabels = ['Image generation', 'Video generation', 'Web search', 'X search']
  for (const label of toolLabels) assert.equal(await page.getByRole('checkbox', { name: label }).isChecked(), true)
  await page.getByRole('checkbox', { name: 'Video generation' }).uncheck()
  await page.setViewportSize({ width: 320, height: 800 })
  assert.equal(await tools.evaluate(el => el.scrollWidth <= el.clientWidth), true)
  const tops = await tools.locator('label').evaluateAll(els => els.map(el => el.getBoundingClientRect().top))
  assert.ok(new Set(tops).size > 1, 'tools wrap at narrow widths')
  await page.setViewportSize({ width: 1280, height: 720 })
  assert.equal(await page.getByLabel('Alpha Context (tokens)').count(), 0)
  const alpha = page.getByRole('button', { name: 'Alpha', exact: true })
  assert.equal(await alpha.getAttribute('aria-describedby'), await alpha.locator('.dsh-subscription-model-id').getAttribute('id'))
  assert.equal(await page.getByRole('checkbox', { name: 'Alpha', exact: true }).getAttribute('aria-describedby'), await alpha.getAttribute('aria-describedby'))
  await alpha.focus()
  await page.keyboard.press('Enter')
  assert.equal(await alpha.getAttribute('aria-expanded'), 'true')
  assert.equal(await alpha.locator('.dsh-subscription-model-action').innerText(), 'Collapse')
  assert.equal(await alpha.locator('.dsh-subscription-model-id').innerText(), 'ID: alpha')
  assert.notEqual(await alpha.evaluate(el => getComputedStyle(el.parentElement.parentElement).borderBottomStyle), 'none')
  await page.getByLabel('Alpha Default reasoning effort').selectOption('high')
  await page.getByLabel('Alpha Context (tokens)').fill('invalid')
  const speedHelp = page.getByRole('button', { name: 'About Alpha Subagent default speed', exact: true })
  await speedHelp.click()
  const speedTip = page.getByRole('tooltip')
  await speedTip.waitFor({ state: 'visible' })
  assert.match(await speedTip.textContent(), /Applies to subsequent subagent requests/)
  assert.equal(await speedTip.evaluate(el => !!el.closest('dialog:modal')), true)
  await speedHelp.click()
  await speedTip.waitFor({ state: 'hidden' })
  await page.getByLabel('Alpha Subagent default speed', { exact: true }).selectOption('fast')
  await page.getByRole('checkbox', { name: 'Alpha', exact: true }).uncheck()
  assert.equal(await alpha.getAttribute('aria-expanded'), 'true')
  await alpha.click()
  await page.getByLabel('Filter models').fill('beta')
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  assert.equal(await page.getByRole('checkbox', { name: 'Aardvark', exact: true }).isChecked(), false)
  await page.getByRole('button', { name: 'Select all', exact: true }).click()
  await page.getByLabel('Filter models').fill('')
  assert.equal(await page.getByRole('checkbox', { name: 'Alpha', exact: true }).isChecked(), true)
  assert.equal(await alpha.getAttribute('aria-expanded'), 'false')
  await page.getByLabel('Filter models').fill('beta')
  assert.equal(await page.evaluate(() => window.collect()), undefined)
  await alpha.waitFor()
  assert.equal(await page.getByLabel('Filter models').inputValue(), 'beta')
  assert.equal(await alpha.getAttribute('aria-expanded'), 'true')
  assert.equal(await page.getByRole('alert').count(), 1)
  assert.equal(await page.getByLabel('Alpha Context (tokens)').inputValue(), 'invalid')
  assert.equal(await page.getByLabel('Alpha Default reasoning effort').inputValue(), 'high')
  assert.equal(await page.getByLabel('Alpha Subagent default speed', { exact: true }).inputValue(), 'fast')
  await page.getByLabel('Filter models').fill('')
  await page.getByLabel('Alpha Context (tokens)').fill('150')
  await page.getByLabel('Alpha Model display name').fill('Zed')
  assert.deepEqual(await buttons.locator('.dsh-subscription-model-name').allTextContents(), ['Zed', 'Aardvark'])
  await page.getByLabel('Filter models').fill('Zed')
  const rename = page.getByLabel('Alpha Model display name')
  await rename.fill('Omega')
  assert.equal(await rename.evaluate(el => el === document.activeElement), true, 'editing a filtered alias keeps focus')
  assert.equal(await rename.inputValue(), 'Omega')
  await rename.fill('Zed')
  await page.getByLabel('Filter models').fill('Aardvark')
  await page.getByLabel('Filter models').fill('')
  assert.equal(await page.getByRole('button', { name: 'Zed', exact: true }).getAttribute('aria-expanded'), 'true')
  const result = await page.evaluate(() => window.collect())
  assert.deepEqual(result.settings.visibleModels, ['beta', 'alpha'])
  assert.deepEqual(result.settings.contextWindows, { alpha: 150 })
  assert.deepEqual(result.settings.tools, { video_generate: false })
  assert.deepEqual(result.settings.subagentSpeeds, { alpha: 'fast' })
  assert.equal(result.settings.modelDisplayNames.alpha, 'Zed')
  assert.deepEqual(result.efforts, [{ model: 'alpha', effort: 'high' }])
  assert.deepEqual(errors, [])
  console.log('Model editor browser checks passed')
} finally { await browser.close() }
