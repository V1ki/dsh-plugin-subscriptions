// Optional offline UI check: PLAYWRIGHT_PATH=/path/to/playwright node test/subscription-usage-browser.mjs
// No running DSH server, real accounts, credentials or model writes. Screenshots use the fixture theme.
import assert from 'node:assert/strict'
import { readdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
const dependencies = await readdir('node_modules/.pnpm')
const packagePath = name => resolve('node_modules/.pnpm', dependencies.find(entry => entry.startsWith(`${name}@`)), 'node_modules', name)
const { build } = await import(pathToFileURL(`${packagePath('rolldown')}/dist/index.mjs`))
const { chromium } = await import(pathToFileURL(`${process.env.PLAYWRIGHT_PATH}/index.mjs`))
const result = await build({
  input: 'test/subscription-usage-browser.fixture.tsx',
  resolve: { alias: { 'react-dom/client': `${packagePath('react-dom')}/client.js` } },
  transform: { define: { 'process.env.NODE_ENV': '"production"' } },
  plugins: [{ name: 'test-css', load(id) { return id.endsWith('.css') ? 'export default {}' : null } }],
  output: { format: 'iife' }, write: false,
})
const code = result.output.find(file => file.type === 'chunk').code
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) })
try {
  const context = await browser.newContext({ viewport: { width: 900, height: 900 } })
  await context.route('**/*', route => route.fulfill({ status: 200, contentType: route.request().url().endsWith('/app.js') ? 'text/javascript; charset=utf-8' : 'text/html; charset=utf-8',
    body: route.request().url().endsWith('/app.js') ? code : '<!doctype html><meta charset="utf-8"><div id="root"></div><script src="/app.js"></script>' }))
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(10_000)
  await page.goto('http://subscription-usage.test/')
  await page.getByRole('button', { name: 'codex', exact: true }).click()
  const badge = page.locator('[data-composer-stats] button')
  await badge.waitFor()
  assert.match(await badge.innerText(), /Default account.*13% used/)
  await page.getByRole('button', { name: 'Toggle settings', exact: true }).click()
  const settings = page.locator('[data-settings]')
  const codex = settings.getByText('Codex (ChatGPT)', { exact: true }).locator('xpath=../..')
  await codex.getByText('13% used', { exact: true }).waitFor()
  const mode = settings.getByRole('combobox', { name: 'Quota percentages', exact: true })
  const calls = () => page.evaluate(() => Number(document.documentElement.dataset.usageCalls))
  const before = await calls()
  await mode.selectOption('remaining')
  await codex.getByText('87% remaining', { exact: true }).waitFor()
  assert.match(await badge.innerText(), /87% remaining/)
  assert.equal(await calls(), before, 'changing preference must not fetch quota')
  await badge.click()
  const panel = page.getByRole('dialog', { name: 'Subscription usage', exact: true })
  const codexPanel = panel.locator('section').filter({ hasText: /^Codex/ })
  await codexPanel.getByText('87% remaining', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  const update = async (name, expected) => {
    await page.getByRole('button', { name, exact: true }).click()
    await codex.getByText(expected, { exact: false }).first().waitFor()
    await page.waitForFunction(expected => document.querySelector('[data-composer-stats] button')?.textContent.includes(expected), expected)
  }
  await update('Boundary usage', '100% remaining')
  await codex.getByText('0% remaining', { exact: true }).waitFor()
  await codex.getByText('5% remaining', { exact: true }).waitFor()
  await codex.getByText('20% remaining', { exact: true }).waitFor()
  const fill = text => codex.getByText(text, { exact: true }).locator('xpath=../..').locator('[aria-hidden] > div')
  assert.match(await fill('100% remaining').getAttribute('style'), /width: 100%;.*success/)
  assert.match(await fill('0% remaining').getAttribute('style'), /width: 0%;.*error/)
  assert.match(await fill('5% remaining').getAttribute('style'), /width: 5%;.*error/)
  assert.match(await fill('20% remaining').getAttribute('style'), /width: 20%;.*warn/)
  await badge.click()
  await codexPanel.getByText('0% remaining', { exact: true }).waitFor()
  await page.screenshot({ path: '/tmp/subscriptions-183-boundaries.png', fullPage: true })
  assert.match(await panel.getByRole('status').innerText(), /100% used \/ 0% remaining/)
  assert.match(await codexPanel.getByText('5% remaining', { exact: true }).locator('xpath=following-sibling::div[1]/div').getAttribute('style'), /width: 5%;.*error/)
  await page.keyboard.press('Escape')
  await update('Unknown usage', 'Unknown quota')
  assert.equal(await codex.getByText('100% remaining', { exact: true }).count(), 0)
  await update('Stale usage', '72% remaining')
  assert.match(await badge.innerText(), /stale/)
  assert.match(await codex.innerText(), /Reset time passed; awaiting refresh/)
  await page.setViewportSize({ width: 360, height: 720 })
  await badge.click()
  await panel.waitFor()
  assert.equal(await panel.evaluate(element => element.scrollWidth <= element.clientWidth), true, 'expired-window text wraps at narrow widths')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 900, height: 900 })
  await page.getByRole('button', { name: 'Fail Codex usage', exact: true }).click()
  await codex.getByText(/Last known usage; refresh unavailable/).waitFor()
  assert.match(await badge.innerText(), /72% remaining.*stale/)
  const priorFocus = await calls()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  assert.equal(await calls(), priorFocus, 'focus uses only existing shared memory')
  await update('Recover usage', '64% remaining')
  assert.doesNotMatch(await badge.innerText(), /stale/)
  assert.equal(await codex.getByText(/Last known usage; refresh unavailable/).count(), 0)
  const other = await context.newPage()
  await other.goto('http://subscription-usage.test/')
  await other.getByRole('combobox', { name: 'Quota percentages', exact: true }).selectOption('used')
  await codex.getByText('36% used', { exact: true }).waitFor()
  assert.match(await badge.innerText(), /36% used/)
  await mode.selectOption('remaining')
  await settings.getByRole('combobox', { name: 'Status-bar quota display', exact: true }).selectOption('hidden')
  await badge.waitFor({ state: 'detached' })
  assert.equal(await mode.inputValue(), 'remaining')
  await codex.getByText('64% remaining', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('combobox', { name: 'Quota percentages', exact: true }).waitFor()
  assert.equal(await page.getByRole('combobox', { name: 'Quota percentages', exact: true }).inputValue(), 'remaining')
  await page.getByRole('combobox', { name: 'Status-bar quota display', exact: true }).selectOption('recent')
  await page.getByRole('button', { name: 'Locale', exact: true }).click()
  await page.getByRole('combobox', { name: '额度百分比', exact: true }).waitFor()
  await page.setViewportSize({ width: 360, height: 720 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.getByRole('button', { name: 'codex', exact: true }).click()
  await badge.waitFor()
  await badge.click()
  const chinesePanel = page.getByRole('dialog', { name: '订阅用量', exact: true })
  await chinesePanel.waitFor()
  const bounds = await chinesePanel.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 360)
  assert.equal(await chinesePanel.evaluate(element => element.scrollWidth <= element.clientWidth), true)
  await page.screenshot({ path: process.env.QUOTA_SCREENSHOT || '/tmp/subscriptions-183-quota.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: settings/badge/details, direction/colors, boundaries/unknown, stale/failure/recovery, cache-only focus, cross-tab persistence, independent hiding, Chinese and narrow layout')
} finally { await browser.close() }
